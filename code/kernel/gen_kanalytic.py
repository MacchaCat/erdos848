"""Generate Erdos848/KAnalytic.lean: the analytic part N >= 1.6e8 from the kernel checks.

Usage: python3 gen_kanalytic.py <path to Erdos848 project>
(run after gen_old_checker.py; reads the piece/chunk counts from the generated files)
"""
import re, sys, os

ROOT = sys.argv[1]
tab = open(os.path.join(ROOT, 'ErdosComp/TabK.lean')).read()
rws = open(os.path.join(ROOT, 'ErdosComp/RowsK.lean')).read()
NP = len(re.findall(r'^def tabP\d+ ', tab, re.M))
NR = len(re.findall(r'^def rowsK\d+ ', rws, re.M))
tmods = sorted(f[:-5] for f in os.listdir(os.path.join(ROOT, 'Erdos848/KTab')) if f.endswith('.lean'))
rmods = sorted(f[:-5] for f in os.listdir(os.path.join(ROOT, 'Erdos848/KRows')) if f.endswith('.lean'))

L = []
w = L.append
w("import Erdos848.KPrime\nimport Erdos848.Tail\nimport ErdosComp.CheckK")
for m in tmods: w(f"import Erdos848.KTab.{m}")
for m in rmods: w(f"import Erdos848.KRows.{m}")
w('''
/-!
# The analytic part `N ≥ 1.6·10⁸`, checked by the kernel (generated by `gen_kanalytic.py`)

* The prime table `tabK` is verified piece by piece (`Erdos848/KTab`): piece `k` is accepted by
  `chainOK` from the start point `tabS k`, and `tabS (k+1)` is the last entry of piece `k`.
* Each certificate row is checked with the table entries it needs, looked up in `treeK`
  (`Erdos848/KRows`).
* The tail constants are checked with `tailTab treeK`.

No `native_decide` is used: every evaluation is `decide +kernel`.
-/

namespace Erdos848

open ErdosComp

set_option maxRecDepth 100000

/-- Every entry of the table is the true state. -/
def ValidT (l : List (ℕ × PSt)) : Prop := ∀ e ∈ l, e.2 = stAt e.1

lemma validT_append {a b : List (ℕ × PSt)} (ha : ValidT a) (hb : ValidT b) : ValidT (a ++ b) := by
  intro e he
  rcases List.mem_append.mp he with h | h
  · exact ha e h
  · exact hb e h

/-- `s` is the last entry of `l`. -/
def lastIs (l : List (ℕ × PSt)) (s : ℕ × PSt) : Bool :=
  match l.getLast? with
  | some e => Nat.beq e.1 s.1 && eqSt e.2 s.2
  | none => false

lemma valid_of_lastIs {l : List (ℕ × PSt)} {s : ℕ × PSt} (hl : ValidT l)
    (h : lastIs l s = true) : s.2 = stAt s.1 := by
  unfold lastIs at h
  split at h
  · rename_i e he
    simp only [Bool.and_eq_true, Nat.beq_eq] at h
    rw [← eqSt_true h.2, ← h.1]
    exact hl e (List.mem_of_getLast? he)
  · exact absurd h Bool.false_ne_true

theorem tabS0_valid : tabS0.2 = stAt tabS0.1 := rfl
''')
for k in range(NP):
    w(f"theorem tabP{k}_valid : ValidT tabP{k} :=\n  chainOK_sound tabP{k} tabS{k}.1 tabS{k}.2 tabS{k}_valid tabP{k}_ok\n")
    if k + 1 < NP:
        w(f"theorem tabLink{k} : lastIs tabP{k} tabS{k+1} = true := by decide +kernel\n")
        w(f"theorem tabS{k+1}_valid : tabS{k+1}.2 = stAt tabS{k+1}.1 :=\n  valid_of_lastIs tabP{k}_valid tabLink{k}\n")
acc = f"tabP{NP - 1}_valid"
for k in range(NP - 2, -1, -1):
    acc = f"(validT_append tabP{k}_valid {acc})"
w(f"theorem tabK_valid : ValidT tabK := by\n  unfold tabK\n  exact {acc}\n")
w('''theorem treeK_match : (matchT treeK tabK).isSome = true := by decide +kernel

theorem treeK_valid : ∀ e ∈ treeK.entries, e.2 = stAt e.1 := by
  obtain ⟨r, hr⟩ := Option.isSome_iff_exists.mp treeK_match
  intro e he
  exact tabK_valid e (by rw [← PTree.matchT_entries treeK tabK r hr]; exact List.mem_append_left _ he)

lemma map_look_valid (t : PTree) (ht : ∀ e ∈ t.entries, e.2 = stAt e.1) (xs : List ℕ) :
    ∀ e ∈ xs.map (fun x => (x, lookDT t x)), e.2 = stAt e.1 := by
  intro e he
  obtain ⟨x, -, rfl⟩ := List.mem_map.mp he
  exact lookDT_eq t ht x

lemma rowTab_valid (r : Row) : ∀ e ∈ rowTab treeK r, e.2 = stAt e.1 := by
  unfold rowTab
  exact map_look_valid treeK treeK_valid (rowPts r)

lemma tailTab_valid : ∀ e ∈ tailTab treeK, e.2 = stAt e.1 := by
  unfold tailTab
  exact map_look_valid treeK treeK_valid _

/-- Every row of `l` passes the checker. -/
def RowsOK (l : List Row) : Prop := ∀ r ∈ l, checkRow (rowTab treeK r) r = true

lemma rowsOK_of_all {l : List Row} (h : l.all (fun r => checkRow (rowTab treeK r) r) = true) :
    RowsOK l := List.all_eq_true.mp h

lemma rowsOK_append {a b : List Row} (ha : RowsOK a) (hb : RowsOK b) : RowsOK (a ++ b) := by
  intro r hr
  rcases List.mem_append.mp hr with h | h
  · exact ha r h
  · exact hb r h
''')
acc = "(rowsOK_of_all rowsK0_ok)"
for i in range(1, NR):
    acc = f"(rowsOK_append {acc} (rowsOK_of_all rowsK{i}_ok))"
w(f"theorem rowsK_ok : RowsOK rowsK := by\n  unfold rowsK\n  exact {acc}\n")
w('''theorem chainK : chain 160000000 (10 ^ 60) rowsK = true := by decide +kernel

theorem rowsK_ne : rowsK ≠ [] := List.ne_nil_of_length_pos (by decide +kernel)

/-- **The analytic part on `[1.6·10⁸, 10⁶⁰]`.** -/
theorem countBounds_mid (N : ℕ) (h1 : 160000000 ≤ N) (h2 : N ≤ 10 ^ 60) : CountBounds N := by
  have hle : ∀ r ∈ rowsK, r.Nlo ≤ r.Nhi := by
    intro r hr
    have := rowsK_ok r hr
    unfold checkRow at this
    simp only [Bool.and_eq_true, decide_eq_true_eq] at this
    exact this.1.1.1.1.1.1.1.1.2
  obtain ⟨r, hr, h1', h2'⟩ := chain_cover (10 ^ 60) N rowsK 160000000 chainK hle rowsK_ne h1 h2
  exact countBounds_of_row (rowTab_valid r) r (rowsK_ok r hr) N h1' h2'

theorem checkTailK : checkTailWith (tailTab treeK) (10 ^ 60) = true := by decide +kernel

/-- **The analytic part for `N ≥ 10⁶⁰`.** -/
theorem countBounds_tail (N : ℕ) (hN : 10 ^ 60 ≤ N) : CountBounds N :=
  countBounds_tail_of tailTab_valid checkTailK N hN

end Erdos848''')
open(os.path.join(ROOT, 'Erdos848/KAnalytic.lean'), 'w').write("\n".join(L) + "\n")
print("pieces", NP, "chunks", NR)
