"""Convert the output of gen2/gen2.c into Lean data for ErdosComp/Check2.lean.

Usage: python3 gen_check2.py <gen2 output dir> <path to Erdos848 project>

Writes (relative to the project):
  ErdosComp/C2Data.lean        the Lemma E2 table `discT`, the structures, the admissible prefix table
  ErdosComp/C2Iv/I*.lean       the intervals, in chunks `ivs0, ivs1, ...`
  ErdosComp/C2Points.txt       the prime-table points needed by Check2 (read by gen_old_checker.py)
"""
import math, os, sys

SRC, ROOT = sys.argv[1], sys.argv[2]
PM = 20000000
IV_PER_CHUNK = 4
CHUNKS_PER_FILE = 8

disc = [tuple(map(int, l.split())) for l in open(os.path.join(SRC, 'disc.txt'))]
adm = [int(l) for l in open(os.path.join(SRC, 'admpre.txt'))]
strs = {}
cur = None
for l in open(os.path.join(SRC, 'strs.txt')):
    t = l.split()
    if t[0] == 'ci':
        cur = int(t[1]); strs[cur] = []
        continue
    e, mask, u, bm, nch = map(int, t[:5])
    strs[cur].append((e, mask, u, bm, list(map(int, t[5:5 + nch]))))

ivs = []
for l in open(os.path.join(SRC, 'iv.txt')):
    t = l.split()
    if t[0] == 'IV':
        ivs.append({'lo': int(t[1]), 'hi': int(t[2]), 'p': [], 'd': []})
    elif t[0] == 'P':
        ivs[-1]['p'].append(list(map(int, t[1:])))
    elif t[0] == 'B':
        nb = int(t[1]); v = list(map(int, t[2:]))
        assert len(v) == 2 * nb
        ivs[-1]['d'].append([(v[2 * i], v[2 * i + 1]) for i in range(nb)])
assert all(len(iv['p']) == 5 and len(iv['d']) == 6 for iv in ivs)

hdr = "import ErdosComp.Check2\n\nnamespace ErdosComp\n\nset_option maxRecDepth 100000\n\n"

def lst(items, ind="  "):
    return "[\n" + ",\n".join(ind + x for x in items) + "]"

out = [hdr, "/-! # Static data of the §10 checker (generated by `gen_check2.py`) -/\n\n"]
SW = [3, 5, 7, 11, 13, 17, 19, 23]
def mlist(m):
    return "[" + ", ".join(str(SW[i]) for i in range(8) if m >> i & 1) + "]"
for i, (e, q, P, S, bn) in enumerate(disc):
    out.append(f"def dE{i} : DiscE := ⟨{e}, {mlist(q)}, {P}, {S}, {bn}⟩\n")
DISC_CHUNK = 4   # entries per kernel declaration (memory)
dchunks = list(range(0, len(disc), DISC_CHUNK))
for k in dchunks:
    out.append(f"\ndef discC{k // DISC_CHUNK} : List DiscE := " +
               lst([f"dE{i}" for i in range(k, min(k + DISC_CHUNK, len(disc)))]) + "\n")
out.append("\ndef discT : List DiscE :=\n  " + " ++ (".join(f"discC{k // DISC_CHUNK}" for k in dchunks) +
           ")" * (len(dchunks) - 1) + "\n\n")
names = {0: 'strsAny', 1: 'strsOdd', 2: 'strsEven'}
STR_CHUNK = 100  # structures per validity declaration
nparts = {}
for ci in range(3):
    L = strs[ci]
    parts = [L[i:i + STR_CHUNK] for i in range(0, len(L), STR_CHUNK)]
    for k, part in enumerate(parts):
        out.append(f"def {names[ci]}{k} : List StrE := " + lst(
            [f"⟨{e}, {mlist(m)}, {u}, {bm}, [{', '.join('dE%d' % c for c in ch)}]⟩" for (e, m, u, bm, ch) in part]) + "\n\n")
    nparts[ci] = len(parts)
    out.append(f"def {names[ci]} : List StrE :=\n  " + " ++ (".join(f"{names[ci]}{k}" for k in range(len(parts))) +
               ")" * (len(parts) - 1) + "\n\n")
out.append("def strsAll : Strs := ⟨strsAny, strsOdd, strsEven⟩\n\n")
ADM_CHUNK = 40   # prefix-table entries per kernel declaration (memory)
achunks = [adm[i:i + ADM_CHUNK] for i in range(0, len(adm), ADM_CHUNK)]
for k, ch in enumerate(achunks):
    out.append(f"def admPre{k} : List Nat := [" + ", ".join(map(str, ch)) + "]\n\n")
out.append("def admPre : List Nat :=\n  " + " ++ (".join(f"admPre{k}" for k in range(len(achunks))) +
           ")" * (len(achunks) - 1) + "\n\nend ErdosComp\n")
open(os.path.join(ROOT, 'ErdosComp/C2Data.lean'), 'w').write("".join(out))

# intervals
os.makedirs(os.path.join(ROOT, 'ErdosComp/C2Iv'), exist_ok=True)
for f in os.listdir(os.path.join(ROOT, 'ErdosComp/C2Iv')):
    os.remove(os.path.join(ROOT, 'ErdosComp/C2Iv', f))
chunks = [ivs[i:i + IV_PER_CHUNK] for i in range(0, len(ivs), IV_PER_CHUNK)]
files = []
for fi in range(0, len(chunks), CHUNKS_PER_FILE):
    name = f"I{fi // CHUNKS_PER_FILE:02d}"
    files.append(name)
    o = [hdr.replace("import ErdosComp.Check2", "import ErdosComp.C2Data")]
    for ci in range(fi, min(fi + CHUNKS_PER_FILE, len(chunks))):
        for ii, iv in enumerate(chunks[ci]):
            k = ci * IV_PER_CHUNK + ii
            ps = ", ".join("⟨" + ", ".join(map(str, p)) + "⟩" for p in iv['p'])
            ds = ", ".join("[" + ", ".join(f"⟨{Y}, {En}⟩" for (Y, En) in d) + "]" for d in iv['d'])
            o.append(f"def iv{k} : Iv2 := ⟨{iv['lo']}, {iv['hi']}, [{ps}], [{ds}]⟩\n\n")
        o.append(f"def ivs{ci} : List Iv2 := [" +
                 ", ".join(f"iv{ci * IV_PER_CHUNK + ii}" for ii in range(len(chunks[ci]))) + "]\n\n")
    o.append("end ErdosComp\n")
    open(os.path.join(ROOT, f'ErdosComp/C2Iv/{name}.lean'), 'w').write("".join(o))
with open(os.path.join(ROOT, 'ErdosComp/C2Iv.lean'), 'w') as f:
    f.write("".join(f"import ErdosComp.C2Iv.{n}\n" for n in files))
    f.write("\nnamespace ErdosComp\n\ndef ivsAll : List Iv2 :=\n  " +
            " ++\n  ".join(f"ivs{c}" for c in range(len(chunks))) + "\n\nend ErdosComp\n")

# table points
pts = set()
def add(x):
    if 0 <= x <= PM:
        pts.add(x)
add(PM)
for iv in ivs:
    N = iv['hi']; r1 = math.isqrt(N); r2 = math.isqrt(2 * N)
    for c, p in enumerate(iv['p']):
        z, dA, zB, dB, z1, z2, dC, pc, pB, Yt, Kt = p
        for x in (z, zB, z1, z2, pc, pB, Yt):
            add(x)
        a = max(pB, min(Yt, r1)); b = max(a, min(Yt, r2))
        add(a); add(b)
    for d in iv['d']:
        for (Y, En) in d:
            add(Y)
            # midQ uses h = max pc (min Y √N) for every case's pc
            for p in iv['p']:
                add(max(p[7], min(Y, r1)))
open(os.path.join(ROOT, 'ErdosComp/C2Points.txt'), 'w').write("\n".join(map(str, sorted(pts))) + "\n")
print("intervals", len(ivs), "chunks", len(chunks), "files", len(files), "points", len(pts))

# ---------------------------------------------------------------- kernel check modules
KD = os.path.join(ROOT, 'Erdos848/K2')
os.makedirs(KD, exist_ok=True)
for f in os.listdir(KD):
    os.remove(os.path.join(KD, f))
khdr = "import ErdosComp.C2Data\nimport ErdosComp.Check2\n\nnamespace ErdosComp\n\nset_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
with open(os.path.join(KD, 'Disc.lean'), 'w') as f:
    f.write(khdr)
    for k in dchunks:
        f.write(f"theorem disc_ok{k // DISC_CHUNK} : discC{k // DISC_CHUNK}.all discOK = true := by decide +kernel\n\n")
    f.write("theorem discT_ok : discT.all discOK = true := by\n  simp only [discT, List.all_append, " +
            ", ".join(f"disc_ok{k // DISC_CHUNK}" for k in dchunks) + ", Bool.and_self]\n\nend ErdosComp\n")
# the number of keys of `keysOf ci e` (completeness is checked KEY_CHUNK keys per declaration)
KEY_CHUNK = 40
SMALLW = [3, 5, 7, 11, 13, 17, 19, 23]
BIGP = [1, 29, 29 * 31, 29 * 31 * 37, 29 * 31 * 37 * 41, 29 * 31 * 37 * 41 * 43]
def nkeys(ci, e):
    n = 0
    for mask in range(256):
        qs = [SMALLW[i] for i in range(8) if mask >> i & 1]
        ok = (5 not in qs) if ci == 0 else (e == 0) if ci == 1 else (e >= 1)
        if not ok:
            continue
        pr = 2 ** e * math.prod(qs)
        n += sum(1 for u in range(6) if pr * BIGP[u] <= 160000000)
    return n
def chunk_fun(name, k):
    if k == 0:
        return "(fun _ hj => absurd hj (by omega))"
    return ("(fun j hj => match j, hj with " + " ".join(f"| {j}, _ => {name}{j}" for j in range(k)) +
            f" | _ + {k}, h => absurd h (by omega))")
khdr2 = khdr.replace("import ErdosComp.Check2\n", "import ErdosComp.Check2Split\n")
for ci in range(3):
    nm = names[ci]
    with open(os.path.join(KD, f'S{ci}.lean'), 'w') as f:
        f.write(khdr2)
        f.write(f"theorem {nm}_sorted : sortedBm {nm} = true := by decide +kernel\n\n")
        for k in range(nparts[ci]):
            f.write(f"theorem {nm}_valid{k} : {nm}{k}.all (strValid discT) = true := by decide +kernel\n\n")
        f.write(f"theorem {nm}_valid : {nm}.all (strValid discT) = true := by\n  simp only [{nm}, List.all_append, " +
                ", ".join(f"{nm}_valid{k}" for k in range(nparts[ci])) + ", Bool.and_self]\n\n")
        for e in range(4):
            K = -(-nkeys(ci, e) // KEY_CHUNK)
            pred = f"(fun k => {nm}.any (fun s => Nat.beq s.e {e} && decide (s.qs = k.1) && Nat.beq s.u k.2))"
            for j in range(K):
                f.write(f"theorem {nm}_comp{e}_{j} : (((keysOf {ci} {e}).drop ({j} * {KEY_CHUNK})).take {KEY_CHUNK}).all\n"
                        f"    {pred} = true := by decide +kernel\n\n")
            f.write(f"theorem {nm}_comp{e} : completeE {ci} {e} {nm} = true := by\n  unfold completeE\n"
                    f"  exact all_of_chunks _ {KEY_CHUNK} {K} _ (by decide +kernel)\n"
                    f"    {chunk_fun(f'{nm}_comp{e}_', K)}\n\n")
        f.write("end ErdosComp\n")
with open(os.path.join(KD, 'Adm.lean'), 'w') as f:
    f.write(khdr2)
    starts = [k * ADM_CHUNK for k in range(len(achunks))]
    for k, ch in enumerate(achunks):
        nxt = f" ++ [{achunks[k + 1][0]}]" if k + 1 < len(achunks) else ""
        f.write(f"theorem admPre_ok{k} : admPreOK (admPre{k}{nxt}) {starts[k]} {ch[0]} = true := by decide +kernel\n\n")
    # glue from the last block backwards
    tail = f"admPre{len(achunks) - 1}"
    f.write(f"theorem admPre_tail{len(achunks) - 1} : admPreOK {tail} {starts[-1]} {achunks[-1][0]} = true :=\n"
            f"  admPre_ok{len(achunks) - 1}\n\n")
    for k in range(len(achunks) - 2, -1, -1):
        tail = f"admPre{k} ++ ({tail})"
        f.write(f"theorem admPre_tail{k} : admPreOK ({tail}) {starts[k]} {achunks[k][0]} = true :=\n"
                f"  admPreOK_glue {achunks[k + 1][0]} _ admPre{k} {starts[k]} {achunks[k][0]} admPre_ok{k} admPre_tail{k + 1}\n\n")
    f.write("theorem admPre_ok : admPreOK admPre 0 0 = true := admPre_tail0\n\nend ErdosComp\n")
# intervals: one module per interval, one theorem per case (the kernel's cache is freed between
# declarations), combined by `checkIv2_of_cases`
CASES = [
    "caseIbQ (lookDT treeK) strsAll {i}.hi ({i}.p.getD 0 dPrm) ({i}.d.getD 0 [])",
    "caseIIQ (lookDT treeK) admPre strsAll {i}.hi ({i}.p.getD 1 dPrm) ({i}.d.getD 1 [])",
    "caseIII1Q (lookDT treeK) admPre strsAll {i}.hi ({i}.p.getD 2 dPrm) ({i}.d.getD 2 [])",
    "caseIII2bQ (lookDT treeK) admPre strsAll {i}.hi ({i}.p.getD 3 dPrm) ({i}.d.getD 3 [])",
    "caseIII2aQ (lookDT treeK) admPre strsAll {i}.hi ({i}.p.getD 4 dPrm) ({i}.d.getD 4 []) ({i}.d.getD 5 [])"]
ivmods = []
for c in range(len(chunks)):
    ks = [c * IV_PER_CHUNK + ii for ii in range(len(chunks[c]))]
    for kk in ks:
        name = f"J{kk:03d}"
        ivmods.append(name)
        with open(os.path.join(KD, f'{name}.lean'), 'w') as f:
            f.write("import ErdosComp.C2Iv\nimport ErdosComp.TabK\nimport ErdosComp.Check2Split\n\nnamespace ErdosComp\n\n" +
                    "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n")
            for ci, ce in enumerate(CASES):
                f.write(f"theorem iv{kk}_c{ci} : below iv{kk}.lo ({ce.format(i=f'iv{kk}')}) = true := by\n"
                        "  decide +kernel\n\n")
            f.write(f"theorem iv{kk}_ok : checkIv2 (lookDT treeK) admPre strsAll iv{kk} = true :=\n" +
                    f"  checkIv2_of_cases _ _ _ iv{kk} rfl rfl (by decide +kernel) " +
                    " ".join(f"iv{kk}_c{ci}" for ci in range(5)) + "\n\nend ErdosComp\n")
    cname = f"C{c:02d}"
    ivmods.append(cname)
    with open(os.path.join(KD, f'{cname}.lean'), 'w') as f:
        f.write("".join(f"import Erdos848.K2.J{kk:03d}\n" for kk in ks))
        f.write("\nnamespace ErdosComp\n\n")
        f.write(f"theorem ivs{c}_ok : ivs{c}.all (checkIv2 (lookDT treeK) admPre strsAll) = true := by\n" +
                f"  simp only [ivs{c}, List.all_cons, List.all_nil, " + ", ".join(f"iv{kk}_ok" for kk in ks) +
                ", Bool.and_true]\n\nend ErdosComp\n")
print("kernel modules: Disc, S0-2, Adm,", len(ivmods), "interval modules")

# ---------------------------------------------------------------- assembly
lo0, hi_last = ivs[0]['lo'], ivs[-1]['hi']
with open(os.path.join(ROOT, 'Erdos848/AnalyticLow.lean'), 'w') as f:
    f.write("import Erdos848.Check2Main\nimport Erdos848.KAnalytic\n")
    f.write("".join(f"import Erdos848.K2.{n}\n" for n in ['Disc', 'S0', 'S1', 'S2', 'Adm'] + [m for m in ivmods if m.startswith('C')]))
    f.write(f'''
/-!
# The analytic part on `[{lo0}, 1.6·10⁸]` (`proof.md` §10), checked by the kernel

Generated by `gen_check2.py`.  The {len(ivs)} intervals of the §10 certificate are checked by
`checkIv2` (`Erdos848/K2/J*.lean`), the static data by `Erdos848/K2/{{Disc,S0,S1,S2,Adm}}.lean`;
`countBounds2_of_iv` turns each accepted interval into `CountBounds2 N`.
-/

namespace Erdos848

open ErdosComp

set_option maxRecDepth 100000

/-- Consecutive intervals from `a` to `b`. -/
def ivChain : ℕ → ℕ → List Iv2 → Bool
  | a, b, [] => a == b
  | a, b, iv :: rest => iv.lo == a && ivChain iv.hi b rest

lemma ivChain_cover (b N : ℕ) : ∀ (ivs : List Iv2) (a : ℕ), ivChain a b ivs = true →
    (∀ iv ∈ ivs, iv.lo ≤ iv.hi) → ivs ≠ [] → a ≤ N → N ≤ b →
    ∃ iv ∈ ivs, iv.lo ≤ N ∧ N ≤ iv.hi := by
  intro ivs
  induction ivs with
  | nil => intro a _ _ h; exact absurd rfl h
  | cons iv rs ih =>
    intro a hc hle _ haN hNb
    simp only [ivChain, Bool.and_eq_true, beq_iff_eq] at hc
    obtain ⟨hra, hc⟩ := hc
    by_cases hN : N ≤ iv.hi
    · exact ⟨iv, List.mem_cons_self .., hra ▸ haN, hN⟩
    · cases rs with
      | nil => simp [ivChain] at hc; omega
      | cons r' rs' =>
        obtain ⟨r'', hmem, h⟩ := ih iv.hi hc (fun x hx => hle x (List.mem_cons_of_mem _ hx))
          (by simp) (by omega) hNb
        exact ⟨r'', List.mem_cons_of_mem _ hmem, h⟩

theorem ivsAll_chain : ivChain {lo0} {hi_last} ivsAll = true := by decide +kernel

theorem ivsAll_ne : ivsAll ≠ [] := List.ne_nil_of_length_pos (by decide +kernel)

theorem ivsAll_ok : ivsAll.all (checkIv2 (lookDT treeK) admPre strsAll) = true := by
  simp only [ivsAll, List.all_append, {", ".join(f"ivs{c}_ok" for c in range(len(chunks)))}, Bool.and_self]

theorem dataOK : DataOK strsAll discT where
  any5 := ⟨strsAny_sorted, strsAny_valid, fun e he => by
    interval_cases e
    exacts [strsAny_comp0, strsAny_comp1, strsAny_comp2, strsAny_comp3]⟩
  odd := ⟨strsOdd_sorted, strsOdd_valid, fun e he => by
    interval_cases e
    exacts [strsOdd_comp0, strsOdd_comp1, strsOdd_comp2, strsOdd_comp3]⟩
  even := ⟨strsEven_sorted, strsEven_valid, fun e he => by
    interval_cases e
    exacts [strsEven_comp0, strsEven_comp1, strsEven_comp2, strsEven_comp3]⟩
  disc := discT_ok

/-- **The analytic part on `[{lo0}, 1.6·10⁸]`.** -/
theorem statement_low (N : ℕ) (h1 : {lo0} ≤ N) (h2 : N ≤ {hi_last}) : Statement N := by
  have hlk : ∀ x, lookDT treeK x = stAt x := lookDT_eq treeK treeK_valid
  have hall := List.all_eq_true.mp ivsAll_ok
  have hle : ∀ iv ∈ ivsAll, iv.lo ≤ iv.hi := by
    intro iv hiv
    have := hall iv hiv
    unfold checkIv2 at this
    split at this
    · simp only [Bool.and_eq_true, decide_eq_true_eq] at this
      omega
    · simp at this
  obtain ⟨iv, hiv, hlo, hhi⟩ := ivChain_cover {hi_last} N ivsAll {lo0} ivsAll_chain hle ivsAll_ne h1 h2
  exact statement_of_bounds2 (countBounds2_of_iv hlk admPre_ok dataOK iv (hall iv hiv) N hlo hhi)

end Erdos848
''')
print("assembly: [", lo0, ",", hi_last, "]")
